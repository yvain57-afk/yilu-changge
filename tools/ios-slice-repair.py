"""Re-extract approved irregular sheets using reviewed silhouette boundaries.
Full-sheet labels avoid both equal-height row clipping and column-clipped weapons.
Component boundaries are extraction candidates: the generated full contact sheets
and source coordinates must be reviewed before acceptance, not file-existence QA.
"""
from pathlib import Path
from PIL import Image, ImageDraw
import ast, json, numpy as np
ROOT=Path(__file__).resolve().parents[1]
node=next(n for n in ast.parse((ROOT/'tools/pr2-art-slice.py').read_text()).body if isinstance(n,ast.FunctionDef) and n.name=='components')
exec(compile(ast.Module(body=[node],type_ignores=[]),'components','exec'))
sets={
 'companions':(['xu','liao','xiahou','lumeng','sunxiang','luxun','huang','machao','jiang'],['Run0','Run1','Thrust'],'g_'),
 'fronts':(['xu','liao','xiahou','lumeng','luxun','zhao','huang','pang','machao'],['Run0','Run1','Hurt'],'g_front_'),
 'heroes':(['guding','shuangji','yitian','qinggang','shuanggu','liannu'],['run','wind','rel','rec'],'g_hero_'),
 'runs':(['guding','shuangji','yitian','qinggang','shuanggu','liannu'],['run0','run1','run2','run3'],'g_hero_'),
 'owners':(['lubu','dian','guan'],['Run0','Run1','Wind','Thrust'],'g_'),
 'bossactions':(['jiao','dong','dian','cao','sunce','zhou','zhang','guan','zhuge'],['wind','rec','hit'],'g_boss_'),
 'enemies':(['jiao','dong','dian','cao','sunce','zhou','zhang','guan','zhuge'],['idle','strike','spent'],'g_boss_'),
}
mp=ROOT/'assets/scripts/formal/manifest.ts';m=json.loads(mp.read_text().split('export const MANIFEST:any=')[1].rstrip(';\n'))
out=ROOT/'art-source/ios-fix20260928';out.mkdir(parents=True,exist_ok=True)
evidence=ROOT/'evidence/IOS-PLAYABLE-FIX-20260928';evidence.mkdir(parents=True,exist_ok=True)
ledger=[]
for name,(ids,poses,pre) in sets.items():
    path=ROOT/f'art-source/formal20260927/{name}-source.png'
    im=Image.open(path).convert('RGBA');a=np.array(im);mask=a[:,:,3]>24
    if name=='enemies':
        # Two adjacent staff silhouettes touch. Reviewed row divide at empty body gap;
        # retain each staff in its own row rather than selecting a merged two-person frame.
        mask[1235:1237,780:1005]=False
    cs=components(mask);big=[r for r in cs if r['area']>2000]
    columns=[sorted([r for r in big if min(len(poses)-1,int((r['box'][0]+r['box'][2])/2/im.width*len(poses)))==col],key=lambda r:r['box'][1]) for col in range(len(poses))]
    assert all(len(c)==len(ids) for c in columns),(name,[len(c) for c in columns])
    tiles=[]
    for col,items in enumerate(columns):
        for i,r in enumerate(items):
            x0,y0,x1,y1=map(int,r['box']);keep=np.zeros(mask.shape,dtype=np.uint8)
            for yy,xx0,xx1 in r['runs']:keep[yy,xx0:xx1]=255
            # Include anti-aliased edges immediately connected to the reviewed silhouette.
            from PIL import ImageFilter
            edge=np.array(Image.fromarray(keep).filter(ImageFilter.MaxFilter(3)))>0
            pix=a[y0:y1,x0:x1].copy();pix[:,:,3]=np.where(edge[y0:y1,x0:x1],pix[:,:,3],0)
            tile=Image.fromarray(pix)
            key=pre+ids[i]+('_' if name in ['heroes','runs','bossactions','enemies'] else '')+poses[col]
            tiles.append((key,ids[i],tile,[x0,y0,x1,y1]))
    atlas=Image.new('RGBA',(2048,2048));x=y=4;rh=0
    # Normalize each actor to its standing body; do not resize bodies per raised weapon.
    refs={id:next(t.height*.83 for k,j,t,b in tiles if j==id) for id in ids}
    board=Image.new('RGB',(len(poses)*250,len(ids)*260),'#87939b');draw=ImageDraw.Draw(board)
    for key,id,tile,box in tiles:
        if x+tile.width+4>2048:x=4;y+=rh+8;rh=0
        assert y+tile.height+4<=2048
        atlas.paste(tile,(x,y));m['frames'][key]={'s':'ios_'+name,'r':[x,y,tile.width,tile.height],'a':[.5,0],'bh':refs[id]}
        ledger.append({'key':key,'source':str(path.relative_to(ROOT)),'sourceBox':box,'sourceSize':list(im.size),'rect':m['frames'][key]['r'],'bodyHeight':refs[id],'review':'contact-sheet-required'})
        idx=ids.index(id);col=next(j for j,pose in enumerate(poses) if key==pre+id+('_' if name in ['heroes','runs','bossactions','enemies'] else '')+pose)
        small=tile.copy();small.thumbnail((240,225));bx=col*250+(250-small.width)//2;by=idx*260+30;board.paste(small,(bx,by),small);draw.text((col*250+5,idx*260+6),key,fill='white')
        tile.save(out/(key+'.png'));x+=tile.width+8;rh=max(rh,tile.height)
    dest=ROOT/f'assets/resources/formal20260927/ios-{name}.png';atlas.crop((0,0,2048,y+rh+4)).save(dest)
    m['sheets']['ios_'+name]='formal20260927/ios-'+name
    board.save(evidence/(name+'-repaired-contact.jpg'))
mp.write_text('// Source geometry generated by tools/ios-slice-repair.py.\nexport const MANIFEST:any='+json.dumps(m,ensure_ascii=False,separators=(',',':'))+';\n')
(out/'slice-ledger.json').write_text(json.dumps(ledger,ensure_ascii=False,indent=2))
print('Re-extracted',len(ledger),'frames; contact review required.')
